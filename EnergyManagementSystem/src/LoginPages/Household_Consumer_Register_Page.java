    private void btnResgisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResgisterActionPerformed
        // TODO add your handling code here:


//        String id = txtId.getText();

        String name = txtName.getText();
        String city = txtCity.getText();
        String street = txtStreet.getText();
        int plot = Integer.parseInt(txtPlotNo.getText());
        long phone = Long.parseLong(txtPhoneNo.getText());
        int solar = Integer.parseInt(txtSolarPanel.getText());
        String password = txtPassword.getText();
        
        if(txtName.getText().isEmpty()||txtCity.getText().isEmpty() || txtStreet.getText().isEmpty() || txtPlotNo.getText().isEmpty()|| txtPhoneNo.getText().isEmpty() || txtSolarPanel.getText().isEmpty()|| "".equals(password)){
            JOptionPane.showMessageDialog(null, "Fill in all the details!");
        } else {
            try{
                Class.forName(DB_DRV);
                con = (Connection) DriverManager.getConnection(DB_URL, DB_USER, DB_PASSWD);
                System.out.printf("Connected to Database! \n");
                
                Statement stmnt = con.createStatement();
                // mysql query to run
                String sql = "INSERT INTO household_consumer (City, Street, Plot_no, Name, Mobile_Number, No_Solar_Panels, Balance, password) VALUES ('"+city+"', '"+street+"', '"+plot+"', '"+name+"', '"+phone+"', '"+solar+"', 0,'"+password+"')";
                stmnt.executeUpdate(sql, Statement.RETURN_GENERATED_KEYS);
                System.out.println("Insert complete.");
                ResultSet rs = stmnt.getGeneratedKeys();
                if(rs.next()){
                    dispose();
                    new Household_Consumer_Login_Page().setVisible(true);
                }
            } catch(Exception e){
                System.out.println(e.getMessage());
            }
        }
    }//GEN-LAST:event_btnResgisterActionPerformed

