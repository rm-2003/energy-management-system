    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        // TODO add your handling code here:
        String id = txtId.getText();
        String name = txtName.getText();
        String city = txtCity.getText();
        String street = txtStreet.getText();
        String size =txtSize.getText();
        int plot = Integer.parseInt(txtPlotNo.getText());
        long phone = Long.parseLong(txtPhoneNo.getText());
        int NON_REC_Permit = Integer.parseInt(txtNON_REC_Permits.getText());
        String password = txtPassword.getText();
        
        if("".equals(txtName.getText()) || "".equals(txtCity.getText()) || "".equals(txtStreet.getText()) || "".equals(txtPlotNo.getText()) || "".equals(txtPhoneNo.getText()) || "".equals(txtNON_REC_Permits.getText())|| "".equals(password)){
            JOptionPane.showMessageDialog(null, "Fill in all the details!");
        } else {
            try{
                Class.forName(DB_DRV);
                con = (Connection) DriverManager.getConnection(DB_URL, DB_USER, DB_PASSWD);
                System.out.printf("Connected to Database! \n");
                
                Statement stmnt = con.createStatement();
                // mysql query to run
                String sql = "INSERT INTO industrial_consumer (Industrial_Consumer_Id, NON_REC_permits, Industry_Size, Name, Mobile_Number, City, Street, Plot_no, Balance_Industry, password) VALUES('"+id+"', '"+NON_REC_Permit+"', '"+size+"','"+name+"','"+phone+"', '"+city+"', '"+street+"', '"+plot+"',  0,'"+password+"')";
                stmnt.executeUpdate(sql, Statement.RETURN_GENERATED_KEYS);
                System.out.println("Insert complete.");
                ResultSet rs = stmnt.getGeneratedKeys();
                if(rs.next()){
                    dispose();
                    new Industrial_Consumer_Login_Page().setVisible(true);
                }
            } catch(Exception e){
                System.out.println(e.getMessage());
            }
        }
    }//GEN-LAST:event_btnRegisterActionPerformed

