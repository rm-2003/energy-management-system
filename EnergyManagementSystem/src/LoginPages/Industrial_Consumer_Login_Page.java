    private void bloginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bloginActionPerformed
        // TODO add your handling code here:
        if(jtuser.getText().equals("")){
            JOptionPane.showMessageDialog(null, "Please fill out username");
        }
        else if (jpassword.getText().equals("")){
            JOptionPane.showMessageDialog(null, "Please enter password");
        }
        else{
            
            try{
                Class.forName(DB_DRV);
                con = (Connection) DriverManager.getConnection(DB_URL, DB_USER, DB_PASSWD);
                System.out.printf("Connected to Database! \n");
                
                String username = jtuser.getText();
                String password = jpassword.getText();
                
                Statement stmnt = con.createStatement();
                // mysql query to run
                String sql = "select * from INDUSTRIAL_CONSUMER where Industrial_Consumer_Id = '"+username+"' and password = '"+password+"'";
                ResultSet rs = stmnt.executeQuery(sql);
                
                if(rs.next()){
                    
                    dispose(); // close login page;
                    new About_Industrial_Consumer(username,password).setVisible(true);
                    
                } else {
                    JOptionPane.showMessageDialog(this, "Username or Password wrong.");
                    jtuser.setText("");
                    jpassword.setText("");
                }
                
            }catch (Exception e){
                System.out.println(e.getMessage());
            }  
        }
        
     
    }//GEN-LAST:event_bloginActionPerformed

