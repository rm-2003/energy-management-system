    public Consumption_Projections(String Username, String Password) {
        Consumption_Projections.user = Username;
        Consumption_Projections.pass = Password;
        initComponents();
        setJMenuBar(new Household_Consumer_Menu_Bar().Consumer_MenuBar(user, pass, this));
        try{
            Class.forName(DB_DRV);
            con = (Connection) DriverManager.getConnection(DB_URL, DB_USER, DB_PASSWD);
            String sql1 = "select * from HOUSEHOLD_CONSUMER where name = '"+user+"' and password = '"+pass+"'";
            Statement stmnt = con.createStatement();
            ResultSet rs1 = stmnt.executeQuery(sql1);
            if(rs1.next()){
                Consumer_ID = rs1.getInt(1);
                System.out.println("Consumer ID is: " + String.valueOf(Consumer_ID));
            }
            else
                System.out.println("couldn't fetch Consumer ID");
            Statement stmnt2 = con.createStatement();
            String sql2 = "SELECT * FROM Consumer_Appliances WHERE Consumer_Id = '" + Consumer_ID + "'";
            ResultSet rs2 = stmnt2.executeQuery(sql2);
            if(rs2.next())
            {
                for(int i=0;i<appQty.length;i++){
                System.out.print(String.valueOf(i) + " ");
                appQty[i]=rs2.getInt(i+2);// sql numbers rows from 1,2,3... whereas our indexes are from 0,1,2...
                finalConsumption[i] = (appQty[i])*(wattage[i])*(runTime[i]);
                finalConsumption[i]/=1000.0;
                weeklyConsumption+=finalConsumption[i];
                System.out.println(String.valueOf(appQty[i])+" "+String.valueOf(wattage[i])
                        +" "+String.valueOf(runTime[i])+" "+String.valueOf(finalConsumption[i])+" ");
            }
            System.out.println("Out of loop");
            }
            else
                System.out.println("Record doesn't exist");
        }
        catch (Exception e){
                System.out.println(e.getMessage());
                
        }
        DefaultTableModel model = new DefaultTableModel();
        model.setColumnIdentifiers(col);
        tblProjections.setModel(model);
        for(int i=0; i<appliance.length;i++)
        {
            System.out.print(String.valueOf(i) + " ");
            Object row[] = {appliance[i], appQty[i],wattage[i],runTime[i],finalConsumption[i]};
            model.addRow(row);
        }
        jScrollPane1.setVisible(true);
        tblProjections.setVisible(true);
        lblWeekly_Consumption.setText(String.valueOf(Math.round(weeklyConsumption)));
    }

