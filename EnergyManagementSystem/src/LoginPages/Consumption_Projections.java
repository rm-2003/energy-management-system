    String[] appliance = {"Refrigerator", "Washing Machine", "Television", "Microwave Oven", "Toaster", "Vacuum Cleaner", "Hair Dryer"};
    int[] appQty= new int[appliance.length];// storing apliance quantities
    static int Consumer_ID;
    int[] runTime = {168, 14, 28, 10, 6, 4, 4};// average weekly running time of eadch appliance
    int[] wattage = {200, 500, 100,800, 700, 1000, 1500};// wattage of each appliance
    float[] finalConsumption = new float[appQty.length];// calculation of total power consumeption
    float weeklyConsumption=0;
    String col[] = {"Appliance", "Quantity", "Unit Consumption(W)","Avg Run Time", "Total Consumption(kWh)"};
