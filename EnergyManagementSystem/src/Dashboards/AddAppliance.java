    private void btnAdd_ApplianceActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdd_ApplianceActionPerformed
        // TODO add your handling code here:
        int ind = cmbAppliances.getSelectedIndex();
        int Consumer_ID=0, appQty=(Integer)spnnrAppliance_Quantity.getValue();
        String[] choice= {"No Choice", "Refrigerator", "WashingMachine", "Television", "MicrowaveOven", "Toaster","VacuumCleaner", "HairDryer"};
        if(ind>=1&&appQty>=0)
        {
            try{
                Statement stmnt = con.createStatement();
                String sql1 = "select * from HOUSEHOLD_CONSUMER where name = '"+user+"' and password = '"+pass+"'";
                ResultSet rs1 = stmnt.executeQuery(sql1);
                if(rs1.next()){
                    Consumer_ID = rs1.getInt(1);
//                  System.out.println("Consumer ID is: " + String.valueOf(Consumer_ID));
                }
                else
                    System.out.println("couldn't fetch Consumer ID");
                Statement stmnt2 = con.createStatement();
                String sql2 = "Update Consumer_Appliances SET "+choice[ind]+" = "+appQty+" WHERE Consumer_Id = "+Consumer_ID+"";
                int res =stmnt2.executeUpdate(sql2, Statement.RETURN_GENERATED_KEYS);
                if(res==1)
                    System.out.println("updated Qty");
            }
            catch (Exception e){
                System.out.println(e.getMessage());
            }
        }
        else
        {
            JOptionPane.showMessageDialog(AddAppliance.this, "Please enter all fields!", "ERROR!", JOptionPane.OK_OPTION);
        }
    }//GEN-LAST:event_btnAdd_ApplianceActionPerformed

